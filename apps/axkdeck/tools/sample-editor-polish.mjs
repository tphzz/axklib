import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const base = process.argv[2] ?? 'http://127.0.0.1:5191';
const output = resolve(process.argv[3] ?? '../../../build/logs/sample-editor/00005');
await mkdir(output,{recursive:true});
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH, headless:true});
const results = [];
try {
    for (const [width,height,zoom] of [[2048,420,1],[1280,360,1],[1280,450,1.25],[800,640,1],[390,740,1]]) {
        const page = await browser.newPage({viewport:{width,height}});
        const errors = [];
        page.on('pageerror',error=>errors.push(error.message));
        await page.goto(`${base}/tools/layout-fixtures/sample-editor.html`);
        const save = page.getByRole('button',{name:'Save',exact:true});
        await save.waitFor();
        await page.evaluate(zoom=>{ document.documentElement.style.zoom=String(zoom); document.querySelector('main').style.height=`${innerHeight / zoom - 40}px`; },zoom);
        const undo = page.getByRole('button',{name:'Undo Sample edit'});
        const screenshot = async name => page.screenshot({path:resolve(output,`${name}-${width}-${zoom}.png`)});
        const footer = await page.locator('.sample-transport').boundingBox();
        assert(footer && footer.y+footer.height <= height+1,'audition strip stays visible in compact dock');
        const flags = await page.locator('.wave-marker span').allTextContents();
        assert.deepEqual(flags,['START','END','LOOP START','LOOP END']);
        await screenshot('waveform');
        const drag = async (locator, dx, dy=0) => {
            const box = await locator.boundingBox(); assert(box);
            await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
            await page.mouse.down(); await page.mouse.move(box.x+box.width/2+dx,box.y+box.height/2+dy,{steps:4}); await page.mouse.up();
        };
        await drag(page.getByRole('slider',{name:'Loop start',exact:true}),24);
        assert(!(await save.isDisabled()),'dragging a marker edits the draft');
        await undo.click(); assert(await save.isDisabled(),'one undo restores the complete marker gesture');
        await page.getByRole('switch',{name:'Zero-cross snap'}).click();
        await page.waitForFunction(()=>document.querySelector('[aria-label="Zero-cross snap"]')?.getAttribute('aria-checked')==='true');
        await page.getByRole('button',{name:'Zoom in',exact:true}).click();
        await page.waitForFunction(()=>document.querySelector('.zoom')?.textContent==='2x');
        await page.getByRole('slider',{name:'Pan zoomed waveform'}).fill('0.5');
        await screenshot('zoom');
        assert(await save.isDisabled(),'zoom and snap do not dirty the Sample');
        await page.getByRole('button',{name:'Fit waveform'}).click();
        await page.getByRole('button',{name:'Play draft',exact:true}).click();
        await page.waitForFunction(()=>document.querySelector('.transport-status')?.textContent==='Playing');
        await page.getByRole('button',{name:'Stop draft preview',exact:true}).click();
        assert(await save.isDisabled(),'audition does not dirty the Sample');
        await page.getByRole('button',{name:'Sample settings',exact:true}).click();
        await screenshot('settings');
        await page.getByRole('button',{name:'Position display: Time / ms'}).click();
        await page.getByRole('spinbutton',{name:'Loop monitor lead-in'}).fill('-80');
        assert(await save.isDisabled(),'display units and monitoring are local settings');
        await page.getByRole('spinbutton',{name:'Tempo',exact:true}).fill('120.25');
        assert(!(await save.isDisabled()));
        await undo.click();
        assert(await save.isDisabled());
        await page.getByRole('tab',{name:'Map/Out',exact:true}).click();
        await screenshot('mix');
        await page.getByRole('button',{name:'Output 2',exact:true}).click();
        const popup = await page.getByRole('listbox',{name:'Output 2'}).boundingBox();
        assert(popup && popup.x>=0 && popup.y>=0 && popup.x+popup.width<=width+1 && popup.y+popup.height<=height+1,'popup fits viewport');
        await screenshot('popup');
        await page.keyboard.press('Escape');
        assert.equal(await page.getByRole('listbox').count(),0);
        await page.getByRole('button',{name:'Level scaling',exact:true}).click();
        assert(await page.getByLabel('Keyboard C-2 to G8').isVisible());
        const handle = page.getByRole('button',{name:/^Point 1:/});
        await handle.focus(); await handle.press('ArrowUp');
        assert(!(await save.isDisabled()));
        await undo.click();
        assert(await save.isDisabled());
        await screenshot('level-scaling');
        await drag(handle,20,4);
        assert(!(await save.isDisabled()),'graph drag updates both coordinates');
        await undo.click(); assert(await save.isDisabled(),'one undo restores both graph coordinates');
        await page.getByRole('button',{name:'Pitch',exact:true}).click();
        await screenshot('pitch');
        await page.getByRole('button',{name:'Expansion & Velocity',exact:true}).click();
        const velocity = page.getByRole('slider',{name:'Low velocity boundary'});
        await velocity.focus(); await velocity.press('ArrowUp');
        assert(!(await save.isDisabled()));
        await undo.click();
        assert(await save.isDisabled());
        await screenshot('velocity');
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'no document overflow');
        assert.deepEqual(errors,[]);
        results.push({width,height,zoom,errors,footer,popup});
        await page.close();
    }
    await writeFile(resolve(output,'polish-results.json'),JSON.stringify(results,null,2)+'\n');
} finally { await browser.close(); }
