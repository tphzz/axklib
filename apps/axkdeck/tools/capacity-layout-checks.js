window.runCapacityLayoutChecks = async function () {
    const failures = [];
    const check = (value, message) => { if (!value) failures.push(message); };
    const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    const wait = async predicate => { for (let i = 0; i < 150 && !predicate(); i++) await new Promise(resolve => setTimeout(resolve, 20)); check(predicate(), 'Timed out waiting for fixture state'); };
    const state = () => JSON.parse(document.querySelector('[data-capacity-state]').textContent);
    const button = (root, text) => [...root.querySelectorAll('button')].find(node => node.textContent.trim() === text);
    await wait(() => document.querySelector('[data-capacity-state]'));
    await frame();
    const colorSample = document.createElement('span');
    colorSample.style.background = 'var(--color-bg-deep)'; document.body.append(colorSample);
    const fieldBackground = getComputedStyle(colorSample).backgroundColor; colorSample.remove();
    check([...document.querySelectorAll('nav select')].every(node => getComputedStyle(node).backgroundColor === fieldBackground && getComputedStyle(node).colorScheme === 'dark'), 'Fixture dropdowns lost the shared dark-field styling');
    check(state().calls === 0, 'Capacity inspection was not lazy');
    const row = document.querySelector('.tree-item-select');
    row.blur();
    row.focus();
    await wait(() => state().calls === 1);
    await wait(() => document.querySelector('[role="tooltip"] .capacity-profile'));
    const tooltip = document.querySelector('[role="tooltip"]');
    await frame();
    const bounds = tooltip.getBoundingClientRect();
    check(tooltip.parentElement === document.body, 'Volume tooltip was not body mounted');
    check(bounds.left >= 7 && bounds.right <= innerWidth - 7 && bounds.top >= 7 && bounds.bottom <= innerHeight - 7, 'Volume tooltip escaped the viewport');
    check(Math.abs(parseFloat(tooltip.style.width) - Math.min(360, (innerWidth - 16) / (row.getBoundingClientRect().width / row.offsetWidth))) < 0.1, 'Volume tooltip lost its preferred width');
    const checkMetrics = root => {
        check(root.querySelectorAll('.capacity-profile').length === 2, 'Both read-only generations were not shown');
        for (const value of root.querySelectorAll('.capacity-metrics dd')) {
            check(getComputedStyle(value).whiteSpace === 'nowrap', 'Capacity number can wrap');
            check(value.scrollWidth <= value.clientWidth + 1, `Capacity number overflowed: ${value.textContent} (${value.scrollWidth}/${value.clientWidth})`);
            const bounds = value.getBoundingClientRect();
            const profile = value.closest('.capacity-profile').getBoundingClientRect();
            const label = value.previousElementSibling.getBoundingClientRect();
            check(bounds.left >= profile.left - 1 && bounds.right <= profile.right + 1, 'Capacity number escaped its profile');
            const sameRow = bounds.top < label.bottom && label.top < bounds.bottom;
            check(sameRow ? label.right <= bounds.left : label.bottom <= bounds.top + 1, 'Capacity label and number overlap');
        }
    };
    checkMetrics(tooltip);
    const cachedCalls = state().calls;
    row.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); await frame();
    check(!document.querySelector('[role="tooltip"]'), 'Tooltip Escape did not dismiss');
    row.focus();
    row.blur(); row.focus(); await frame();
    check(!!document.querySelector('[role="tooltip"]'), 'Keyboard focus did not restore tooltip');
    row.click(); await frame();
    await wait(() => document.querySelector('[aria-label="Volume inspector"]'));
    check(state().calls === cachedCalls, 'Selection did not reuse tooltip inspection');
    const inspector = document.querySelector('[aria-label="Volume inspector"]');
    check(!button(inspector, 'a4k/a5k') && !button(inspector, 'a3k'), 'Inspector still has a generation toggle');
    const section = [...inspector.querySelectorAll('button')].find(node => node.textContent.includes('Sampler Capacity'));
    check(section?.getAttribute('aria-expanded') === 'false', 'Fitting capacity was not collapsed by default');
    section.click(); await frame();
    checkMetrics(inspector);
    const properties = inspector.querySelector('[data-inspector-section="properties"]');
    check([...inspector.querySelectorAll('.capacity-metrics dt')].every(node => getComputedStyle(node).fontSize === getComputedStyle(properties.querySelector('dt')).fontSize), 'Capacity label typography differs from Properties');
    check([...inspector.querySelectorAll('.capacity-metrics dd, .capacity-profile-heading')].every(node => getComputedStyle(node).fontSize === getComputedStyle(properties.querySelector('dd')).fontSize), 'Capacity value typography differs from Properties');
    check(!inspector.textContent.includes('Load peak') && !inspector.textContent.includes('Load baseline'), 'Technical table rows remain');
    check(inspector.querySelector('.capacity-metrics dd').textContent === '121.1 / 512 KiB', 'Inspector did not show loading maximum');
    const help = button(inspector, 'Parameter memory');
    help.focus(); await frame();
    check(document.querySelector('[role="tooltip"]')?.textContent.includes(`${(124000).toLocaleString()} bytes`), 'Exact-byte help was lost');
    section.click(); await frame();
    check(!document.querySelector('[role="tooltip"]'), 'Collapsed panel left metric help open');
    const inspectorMode = document.querySelector('[aria-label="Inspector scenario"]');
    const changeInspector = async value => {
        inspectorMode.value = value; inspectorMode.dispatchEvent(new Event('change', { bubbles: true }));
        await wait(() => value === 'ERROR' ? inspector.querySelector('[role="alert"]') : inspector.querySelector('.capacity-profile-heading span')?.textContent === ({ FITS: 'Fits', DOES_NOT_FIT: 'Does not fit' })[value]);
        await frame();
    };
    await changeInspector('DOES_NOT_FIT');
    check(section.getAttribute('aria-expanded') === 'true', 'Violation did not auto-expand');
    checkMetrics(inspector);
    check(!inspector.querySelector('.capacity-reason'), 'Parameter overflow prose was repeated');
    section.click(); await frame();
    row.click(); await frame();
    check(section.getAttribute('aria-expanded') === 'false', 'Manual capacity collapse was lost');
    await changeInspector('ERROR');
    check(section.getAttribute('aria-expanded') === 'false', 'Failed inspection auto-expanded');
    await changeInspector('FITS');
    const pane = document.querySelector('[data-background-pane]');
    pane.scrollTop = 80;
    const before = pane.getBoundingClientRect(); const scroll = pane.scrollTop;
    button(document, 'Apply change').focus();
    button(document, 'Apply change').click();
    await wait(() => document.querySelector('[aria-label="Sampler load capacity"]'));
    const dialog = document.querySelector('[aria-label="Sampler load capacity"]');
    const dialogBounds = dialog.getBoundingClientRect();
    check(dialogBounds.left >= 0 && dialogBounds.right <= innerWidth && dialogBounds.top >= 0 && dialogBounds.bottom <= innerHeight, 'Capacity dialog escaped the viewport');
    for (const control of dialog.querySelectorAll('button')) {
        const bounds = control.getBoundingClientRect();
        check(bounds.left >= dialogBounds.left && bounds.right <= dialogBounds.right, 'Capacity action escaped the dialog');
    }
    const footer = [...dialog.querySelectorAll('.dialog-footer-actions button')];
    check(footer.length === 2 && Math.abs(footer[0].getBoundingClientRect().height - footer[1].getBoundingClientRect().height) < 0.5, 'Footer button heights differ');
    check(footer.every(node => getComputedStyle(node).marginTop === '0px' && getComputedStyle(node).marginBottom === '0px'), 'Footer button margins differ');
    check(pane.getBoundingClientRect().width === before.width && pane.scrollTop === scroll, 'Modal changed background geometry or scroll');
    check(state().writes === 0, 'Review wrote before submission');
    button(dialog, 'Cancel').click(); await frame();
    check(state().writes === 0 && pane.scrollTop === scroll, 'Cancel wrote or changed background scroll');
    const mode = document.querySelector('[aria-label="Capacity scenario"]');
    mode.value = 'DOES_NOT_FIT'; mode.dispatchEvent(new Event('change', { bubbles: true }));
    button(document, 'Apply change').click();
    await wait(() => document.querySelector('[aria-label="Sampler load capacity"]'));
    const hard = document.querySelector('[aria-label="Sampler load capacity"]');
    check(button(hard, 'Continue').disabled, 'Capacity failure can be submitted');
    button(hard, 'Cancel').click(); await frame();
    mode.value = 'ERROR'; mode.dispatchEvent(new Event('change', { bubbles: true }));
    button(document, 'Apply change').click();
    await wait(() => state().outcome === 'Capacity service disconnected');
    check(!document.querySelector('[role="dialog"]'), 'Initial inspection error opened a capacity review');
    mode.value = 'FITS'; mode.dispatchEvent(new Event('change', { bubbles: true }));
    button(document, 'Apply change').click();
    await wait(() => document.querySelector('[aria-label="Sampler load capacity"]'));
    const failed = document.querySelector('[aria-label="Sampler load capacity"]');
    mode.value = 'ERROR'; mode.dispatchEvent(new Event('change', { bubbles: true }));
    button(failed, 'a3k').click();
    await wait(() => failed.textContent.includes('Capacity service disconnected'));
    check(button(failed, 'Continue').disabled, 'Inspection error can be submitted');
    check(!failed.querySelector('.capacity-summary').textContent.includes('Volume 1:'), 'Inspection error retained an earlier admission');
    check(state().writes === 0, 'Blocked capacity scenarios wrote');
    button(failed, 'Cancel').click(); await frame();
    mode.value = 'FITS'; mode.dispatchEvent(new Event('change', { bubbles: true }));
    button(document, 'Apply change').click();
    await wait(() => document.querySelector('[aria-label="Sampler load capacity"]'));
    button(document.querySelector('[aria-label="Sampler load capacity"]'), 'Continue').click();
    await wait(() => state().writes === 1);
    check(!document.querySelector('[role="dialog"]'), 'Fitting review did not close');
    await changeInspector('DOES_NOT_FIT');
    return { failures, state: state(), backgroundRestored: pane.scrollTop === scroll };
};
