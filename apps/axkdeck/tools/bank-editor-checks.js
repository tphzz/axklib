window.runBankEditorChecks = async function () {
    const failures = [];
    const check = (condition, message) => { if (!condition) failures.push(message); };
    const settle = () => new Promise(resolve => setTimeout(resolve, 100));
    const labelled = name => document.querySelector(`[aria-label="${name}"]`);
    const button = name => [...document.querySelectorAll('button')].find(node => node.textContent.trim() === name);
    const field = name => document.querySelector(`input[type=number][aria-label="${name}"]`);
    const change = async (name, value) => {
        const input = field(name);
        if (!input) throw new Error(`Missing input ${name}`);
        check(!input.disabled, `${name} is editable`);
        input.value = String(value);
        input.dispatchEvent(new Event('input', {bubbles: true}));
        input.dispatchEvent(new Event('change', {bubbles: true}));
        input.dispatchEvent(new FocusEvent('blur'));
        await settle();
    };
    const navigate = async (tab, sub) => {
        [...document.querySelectorAll('[role=tab]')].find(node => node.textContent.trim() === tab).click();
        await settle();
        [...labelled('Sample subpages').querySelectorAll('button')].find(node => node.textContent.trim() === sub).click();
        await settle();
    };
    for (let i = 0; i < 40 && !labelled('Preview sample'); i++) await settle();
    await settle();
    check(labelled('Preview sample')?.selectedOptions[0]?.textContent === 'Member A', 'First resolved member is the preview');
    check(!button('Waveform'), 'Bank has no waveform editor');
    check(!field('Loop Tempo'), 'Bank Sample Info has no sample-only tempo helper');
    await navigate('Map/Out', 'Mix & Key');
    check(field('Level').value === '' && field('Level').placeholder === '---', 'Inherited level is ---');
    check(!button('Save').disabled === false, 'Inherited bank starts clean');
    await change('Level', 81);
    check(!button('Save').disabled, 'Changing inherited value enables Save');
    labelled('Next preview sample').click(); await settle();
    check(field('Level').value === '81', 'Preview change cannot change bank override');
    check(document.querySelector('.device-editor strong').textContent === 'Bank A', 'Preview never changes editing target');
    labelled('Use sample values for Level').click(); await settle();
    check(field('Level').value === '' && button('Save').disabled, 'Clearing a new override returns clean inherited state');
    await change('Level', 82); button('Save').click(); await settle();
    check(labelled('Write count').textContent === '1' && button('Save').disabled, 'Save finishes once and cleans draft');
    check(field('Level').value === '82', 'Saved override reloads');
    check(labelled('Preview sample').selectedOptions[0].textContent === 'Member B', 'Save retains preview member');
    labelled('Use sample values for Level').click(); await settle(); button('Save').click(); await settle();
    check(labelled('Write count').textContent === '2' && field('Level').value === '', 'Clear saved override persists inheritance');
    await navigate('EG', 'Amplitude');
    await change('Attack rate', 100);
    check(field('Decay rate').value === '91' && field('Release rate').value === '92', 'Activation seeds all envelope rates from preview');
    labelled('Undo Sample edit').click(); await settle();
    check(field('Attack rate').value === '' && field('Decay rate').value === '' && button('Save').disabled, 'Group activation undoes atomically');
    button('Select B').click(); await settle();
    check(field('Attack rate') && labelled('Sample subpages').querySelector('[aria-pressed=true]').textContent === 'Amplitude', 'Bank switch retains tab and subtab');
    button('Select A').click(); await settle();
    labelled('Play draft').click();
    for (let i = 0; i < 30 && !labelled('Stop draft preview'); i++) await settle();
    check(!!labelled('Stop draft preview'), 'Playing member audio remains owned by bank transport');
    labelled('Previous preview sample').click(); await settle();
    check(!!labelled('Play draft'), 'Changing preview stops bank playback');
    labelled('Play draft').click();
    for (let i = 0; i < 30 && !labelled('Stop draft preview'); i++) await settle();
    await change('Attack rate', 110);
    check(!!labelled('Play draft'), 'Editing stops bank preview');
    labelled('Undo Sample edit').click(); await settle();
    await navigate('Filter', 'Sample EQ');
    const coefficients = labelled('Show coefficient response');
    coefficients.click(); await settle();
    check(coefficients.getAttribute('aria-pressed') === 'true', 'Coefficient response is visible');
    const curve = document.querySelector('[data-trace=coefficients]');
    check(curve && curve.getAttribute('d').length > 100 && !/NaN|Infinity/.test(curve.getAttribute('d')), 'Inherited coefficient curve is finite and rendered');
    await change('EQ gain (dB)', 3);
    check(field('EQ frequency selection').value !== '' && field('EQ width').value !== '', 'EQ activates as one unit');
    labelled('Undo Sample edit').click(); await settle();
    await navigate('MIDI/CTRL', 'Control');
    await change('Control 1 Range', 20);
    check(field('Control 6 Range').value !== '', 'Controller matrix activates as one unit');
    labelled('Undo Sample edit').click(); await settle();
    check(button('Save').disabled, 'Matrix undo restores inheritance');
    const panel = document.querySelector('.sample-panel');
    if (panel.scrollHeight > panel.clientHeight + 50) {
        panel.scrollTop = 50;
        await settle();
        button('Select B').click(); await settle();
        check(document.querySelector('.sample-panel').scrollTop === 50, 'Bank switch retains page scroll position');
        button('Select A').click(); await settle();
    }
    check(document.documentElement.scrollWidth <= innerWidth + 1, 'No horizontal viewport overflow');
    for (const input of document.querySelectorAll('input,select')) {
        const rect = input.getBoundingClientRect();
        if (rect.width && rect.height) check(rect.right <= innerWidth + 1 && rect.left >= -1, `Control fits: ${input.getAttribute('aria-label')}`);
    }
    await navigate('EG', 'Amplitude');
    const trace = document.querySelector('.response-trace');
    check(trace && trace.getAttribute('d').length > 20 && !/NaN|Infinity/.test(trace.getAttribute('d')), 'Inherited envelope is finite and rendered');
    return { failures };
};
